// Writes README.md from profile.config.json. Run it after you change the project list:
//   node scripts/readme.mjs
// The images it links to are rebuilt by the "Update profile" workflow on the output branch.
import { readFile, writeFile } from 'node:fs/promises';

const config = JSON.parse(await readFile(new URL('../profile.config.json', import.meta.url), 'utf8'));
const raw = `https://raw.githubusercontent.com/${config.login}/${config.login}/${config.outputBranch}`;

const cardLink = (card) => (card.repo ? `https://github.com/${config.login}/${card.repo}` : card.link);
const cardImage = (card) =>
  `<a href="${cardLink(card)}"><img src="${raw}/cards/${card.slug}.svg" width="49%" alt="${card.title}: ${card.tagline}"></a>`;

const sections = config.groups.map((group) => {
  const rows = [];
  for (let i = 0; i < group.cards.length; i += 2) rows.push(group.cards.slice(i, i + 2).map(cardImage).join('\n'));
  return `### ${group.title}\n\n<p>\n${rows.join('\n')}\n</p>`;
});

const prSearch = `https://github.com/pulls?q=${encodeURIComponent(`is:pr author:${config.login} -user:${config.login}`)}`;

const readme = `<!-- Generated by scripts/readme.mjs from profile.config.json. Edit those files, not this one. -->
<a href="https://likheet.is-a.dev">
  <img src="${raw}/room.svg" width="100%" alt="A live drawing of Likheet's desk in Sydney: the real sky and weather outside the window, the latest push on the monitor, and a cat that sleeps when Likheet does.">
</a>

<h3 align="center">Hi, I'm Likheet. I build fast native apps, AI tools and browser extensions.</h3>

<p align="center">
  Master of IT student at UNSW, Sydney &nbsp;·&nbsp; Rust · TypeScript · Python · LLMs
  <br>
  <a href="https://likheet.is-a.dev"><b>Portfolio</b></a> &nbsp;·&nbsp;
  <a href="https://www.linkedin.com/in/likheet/"><b>LinkedIn</b></a> &nbsp;·&nbsp;
  <a href="https://www.kaggle.com/likheet"><b>Kaggle</b></a> &nbsp;·&nbsp;
  <a href="mailto:likheet.s@gmail.com"><b>Email</b></a>
</p>

${sections.slice(0, 2).join('\n\n')}

### Open source

<a href="${prSearch}"><img src="${raw}/open-source.svg" width="100%" alt="Pull requests to open-source projects, with their current status"></a>

${sections.slice(2).join('\n\n')}

<details>
<summary><b>Earlier projects</b></summary>
<br>

- [AI News App](https://github.com/${config.login}/AI-News-App): voice-controlled news app (Alan AI, React)
- [Goblin](https://github.com/${config.login}/goblin): AI to-do app that breaks big tasks into subtasks (Next.js, OpenAI)
- [DesiQna frontend](https://github.com/${config.login}/sde-intern): my 2023 internship work
- [LeetCode solutions](https://github.com/${config.login}/Leetcode-problems)
- First web projects, 2023: [dictionary](https://github.com/${config.login}/dictionary), [to-do list](https://github.com/${config.login}/todo-list), [Starbucks page](https://github.com/${config.login}/starbucks-landing-page), [Coca-Cola page](https://github.com/${config.login}/coke-landing-page)

</details>

<p align="center"><sub>The room at the top is redrawn every 15 minutes from live data. <a href="scripts">See how it works.</a></sub></p>
`;

await writeFile(new URL('../README.md', import.meta.url), readme);
console.log('README.md written.');
